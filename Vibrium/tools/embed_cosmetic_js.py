#!/usr/bin/env python3
"""Embeds c++/adblock/cosmetic_content.js into a C++ include file.

The script is stored as a byte array rather than a string literal because MSVC
limits string literals to about 16 KB. Comment-only lines and indentation are
removed to keep what is sent to every page small.

  embed_cosmetic_js.py           regenerate c++/adblock/cosmetic_content_js.inc
  embed_cosmetic_js.py --check   exit 1 if the .inc is stale (used by CI)
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "c++" / "adblock" / "cosmetic_content.js"
OUTPUT = ROOT / "c++" / "adblock" / "cosmetic_content_js.inc"


def render() -> str:
    lines = []
    for line in SOURCE.read_text(encoding="utf-8").replace("\r\n", "\n").split("\n"):
        stripped = line.strip()
        if stripped and not stripped.startswith("//"):
            lines.append(stripped)
    data = ("\n".join(lines) + "\n").encode("utf-8")
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    return (
        "// GENERATED by tools/embed_cosmetic_js.py from cosmetic_content.js.\n"
        "// Do not edit; run the tool again. CI fails if this file is stale.\n"
        "static const unsigned char kCosmeticContentScript[] = {\n"
        + "\n".join(rows)
        + "\n};\n"
    )


def main() -> int:
    expected = render()
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != expected:
            print(f"{OUTPUT.name} is stale; run tools/embed_cosmetic_js.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.name} is up to date")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({len(expected)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
